import { test, expect } from '@playwright/test'
import { loginWith, createBlog } from './helpers'
const user = { username: 'alice', name: 'Alice Example', password: 'password123' }
test.describe('Blog app — Part 5', () => {
  test.beforeEach(async ({ page, request }) => {
    const reset = await request.post('/api/testing/reset')
    expect(reset.status()).toBe(204)
    const created = await request.post('/api/users', { data: user })
    expect(created.status()).toBe(201)
    await page.goto('/')
  })
  test('5.17 login form is accessible by default', async ({ page }) => {
    await page.getByRole('link', { name: 'login' }).click()
    await expect(page.getByLabel('username')).toBeVisible()
    await expect(page.getByLabel('password')).toBeVisible()
  })
  test('5.18 and 5.28 valid login succeeds', async ({ page }) => {
    await page.getByRole('link', { name: 'login' }).click()
    await loginWith(page)
    await expect(page.getByText('Alice Example logged in')).toBeVisible()
  })
  test('5.18 and 5.28 invalid login fails', async ({ page }) => {
    await page.getByRole('link', { name: 'login' }).click()
    await loginWith(page, 'alice', 'incorrect')
    await expect(page.getByRole('alert')).toContainText('wrong credentials')
    await expect(page.getByText('Alice Example logged in')).toHaveCount(0)
  })
  test.describe('when logged in', () => {
    test.beforeEach(async ({ page }) => {
      await page.getByRole('link', { name: 'login' }).click()
      await loginWith(page)
      await expect(page.getByText('Alice Example logged in')).toBeVisible()
    })
    test('5.19 and 5.28 creates a blog', async ({ page }) => {
      await createBlog(page, 'Playwright created this')
      await expect(page.getByText('Playwright created this').first()).toBeVisible()
    })
    test('5.20 and 5.28 likes a blog', async ({ page }) => {
      await createBlog(page, 'Blog to like')
      const item = page.getByTestId('blog-item').filter({ hasText: 'Blog to like' })
      await item.getByRole('button', { name: 'view' }).click()
      await item.getByRole('button', { name: 'like' }).click()
      await expect(item.getByTestId('likes-count')).toHaveText('1')
    })
    test('5.21 and 5.28 creator can remove a blog', async ({ page }) => {
      await createBlog(page, 'Blog to remove')
      const item = page.getByTestId('blog-item').filter({ hasText: 'Blog to remove' })
      await item.getByRole('button', { name: 'view' }).click()
      page.once('dialog', dialog => dialog.accept())
      await item.getByRole('button', { name: 'remove' }).click()
      await expect(page.getByTestId('blog-item').filter({ hasText: 'Blog to remove' })).toHaveCount(0)
    })
    test('5.22 only creator sees remove button', async ({ page, request }) => {
      await createBlog(page, 'Owned by Alice')
      const other = await request.post('/api/users', { data: { username: 'bob', name: 'Bob Example', password: 'password123' } })
      expect(other.status()).toBe(201)
      const login = await request.post('/api/login', { data: { username: 'bob', password: 'password123' } })
      expect(login.status()).toBe(200)
      const { token } = await login.json()
      const created = await request.post('/api/blogs', { headers: { Authorization: `Bearer ${token}` }, data: { title: 'Owned by Bob', author: 'Bob', url: 'https://example.com/bob' } })
      expect(created.status()).toBe(201)
      await page.reload()
      const mine = page.getByTestId('blog-item').filter({ hasText: 'Owned by Alice' })
      const theirs = page.getByTestId('blog-item').filter({ hasText: 'Owned by Bob' })
      await mine.getByRole('button', { name: 'view' }).click()
      await theirs.getByRole('button', { name: 'view' }).click()
      await expect(mine.getByRole('button', { name: 'remove' })).toBeVisible()
      await expect(theirs.getByRole('button', { name: 'remove' })).toHaveCount(0)
    })
    test('5.23 blogs are ordered by likes descending', async ({ page }) => {
      await createBlog(page, 'Low likes')
      await createBlog(page, 'High likes')
      const high = page.getByTestId('blog-item').filter({ hasText: 'High likes' })
      await high.getByRole('button', { name: 'view' }).click()
      await high.getByRole('button', { name: 'like' }).click()
      await expect(high.getByTestId('likes-count')).toHaveText('1')
      const entries = page.locator('.blog-list-entry')
      await expect(entries.first()).toContainText('High likes')
      await expect(entries.nth(1)).toContainText('Low likes')
    })
    test('5.24–5.26 navigation and routed blog detail', async ({ page }) => {
      await createBlog(page, 'Routed blog')
      await page.getByRole('link', { name: 'Routed blog' }).click()
      await expect(page).toHaveURL(/\/blogs\/[a-f\d]+$/)
      await expect(page.getByText('https://example.com')).toBeVisible()
      await page.getByRole('link', { name: 'blogs', exact: true }).click()
      await expect(page).toHaveURL(/\/$/)
    })
  })
})
