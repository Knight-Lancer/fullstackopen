const express = require('express')
const mongoose = require('mongoose')
const config = require('./utils/config')
const logger = require('./utils/logger')
const middleware = require('./utils/middleware')
const blogsRouter = require('./controllers/blogs')
const usersRouter = require('./controllers/users')
const loginRouter = require('./controllers/login')
const app = express()
if (!config.MONGODB_URI) throw new Error('MONGODB_URI (or TEST_MONGODB_URI in test mode) is required')
if (!config.SECRET) throw new Error('SECRET environment variable is required')
const databaseReady = mongoose.connect(config.MONGODB_URI, { family: 4 })
  .then(() => logger.info('Connected to MongoDB'))
  .catch((error) => { logger.error('MongoDB connection failed:', error.message); throw error })
app.use(express.json())
app.use(middleware.requestLogger)
app.use(middleware.tokenExtractor)
app.use('/api/blogs', blogsRouter)
app.use('/api/users', usersRouter)
app.use('/api/login', loginRouter)
if (process.env.NODE_ENV === 'test') app.use('/api/testing', require('./controllers/testing'))
app.use(middleware.unknownEndpoint)
app.use(middleware.errorHandler)
module.exports = app
module.exports.databaseReady = databaseReady
